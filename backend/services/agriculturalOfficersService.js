export const getOfficers = ({ district = "", taluk = "", category = "" } = {}) => {
  let list = [...AGRICULTURAL_OFFICERS];

  if (district && district !== "All" && district !== "All Districts") {
    const distLower = district.toLowerCase();
    list = list.filter(o =>
      o.district.toLowerCase() === distLower ||
      o.district === "All Districts"
    );
  }

  if (taluk && taluk !== "All" && taluk !== "All Taluks") {
    const talukLower = taluk.toLowerCase();
    const talukMatches = list.filter(o => o.taluk.toLowerCase() === talukLower);
    if (talukMatches.length > 0) {
      list = [...talukMatches, ...list.filter(o => o.district === "All Districts")];
    }
  }

  if (category && category !== "All") {
    const catLower = category.toLowerCase();
    list = list.filter(o => o.category.toLowerCase().includes(catLower));
  }

  return list;
};

export const getKarnatakaAgriculturalOfficers = getOfficers;
